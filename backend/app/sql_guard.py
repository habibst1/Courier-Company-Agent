# Belt and braces for functions sqlglot does model: never let these through, whatever the parse.
_DENIED_FUNCTION = re.compile(
    r"^(set_config|current_setting|generate_series|nextval|setval|currval|lastval|pg_\w*|lo_\w*"
    r"|dblink\w*|txid_\w*|\w*_to_xml\w*|query_to_\w*|copy\w*)$"
)

_FORBIDDEN_NODES = tuple(
    getattr(exp, name)
    for name in (
        "Insert",
        "Update",
        "Delete",
        "Merge",
        "Create",
        "Drop",
        "Alter",
        "Command",
        "Into",
        "Lock",
        "Set",
        "SetItem",
        "Transaction",
        "Commit",
        "Rollback",
        "Copy",
        "TruncateTable",
        "Grant",
        "Revoke",
        "Pragma",
        "Use",
        "Describe",
        "Kill",
        "Show",
        "Analyze",
        "Execute",
    )
    if hasattr(exp, name)
)

_LEADING_NAME = re.compile(r'\s*"?([A-Za-z_][A-Za-z0-9_$]*)')


class UnsafeQueryError(ValueError):
    """The query isn't a single plain SELECT over the allowed views."""


def validate_select(sql: str, *, max_rows: int) -> str:
    """Return normalized SQL that reads at most max_rows + 1 rows, or raise UnsafeQueryError.

    One extra row is allowed so the caller can tell the result was truncated.
    """
    text = sql.strip().rstrip(";").strip()
    if not text:
        raise UnsafeQueryError("the query is empty")
    if len(text) > MAX_QUERY_CHARS:
        raise UnsafeQueryError(f"the query is longer than {MAX_QUERY_CHARS} characters")
    try:
        statements = [s for s in sqlglot.parse(text, read="postgres") if s is not None]
    except SqlglotError as exc:
        raise UnsafeQueryError(f"PostgreSQL syntax error: {str(exc).splitlines()[0]}") from exc
    if len(statements) != 1:
        raise UnsafeQueryError("send exactly one statement")

    tree = statements[0]
    if not isinstance(tree, (exp.Select, exp.SetOperation)):
        raise UnsafeQueryError("only SELECT queries are allowed")

    cte_names = {cte.alias_or_name.lower() for cte in tree.find_all(exp.CTE)}
    for node in tree.walk():
        if isinstance(node, _FORBIDDEN_NODES):
            raise UnsafeQueryError(f"{node.key.upper()} is not allowed; only read data with SELECT")
        if isinstance(node, exp.Table):
            _check_table(node, cte_names)
        elif isinstance(node, exp.Dot) and isinstance(node.expression, exp.Func):
            raise UnsafeQueryError("call functions without a schema prefix")
        elif isinstance(node, exp.Func):
            _check_function(node)

    return _cap_rows(tree, max_rows + 1).sql(dialect="postgres")


def _check_table(node: exp.Table, cte_names: set[str]) -> None:
    if not isinstance(node.this, exp.Identifier):
        raise UnsafeQueryError("functions are not allowed in FROM; query the views directly")
    name, schema = node.name.lower(), (node.db or "").lower()
    if node.catalog or schema not in ALLOWED_SCHEMAS:
        raise UnsafeQueryError(f"schema {schema!r} is not available; use the views unqualified")
    if schema == "" and name in cte_names:
        return
    if name not in ALLOWED_VIEWS:
        allowed = ", ".join(sorted(ALLOWED_VIEWS))
        raise UnsafeQueryError(f"there is no table {name!r}; the only views are {allowed}")


def _check_function(node: exp.Func) -> None:
    if isinstance(node, exp.Anonymous):
        name = node.name.lower()
        if name not in ALLOWED_UNMODELED_FUNCTIONS:
            raise UnsafeQueryError(f"function {name}() is not allowed")
        return
    match = _LEADING_NAME.match(node.sql(dialect="postgres"))
    if match and _DENIED_FUNCTION.match(match.group(1).lower()):
        raise UnsafeQueryError(f"function {match.group(1).lower()}() is not allowed")


def _cap_rows(tree: exp.Expression, limit: int) -> exp.Expression:
    if isinstance(tree, exp.Select) and not tree.args.get("fetch"):
        current = tree.args.get("limit")
        value = current.expression if isinstance(current, exp.Limit) else None
        if not (isinstance(value, exp.Literal) and value.is_int and int(value.this) <= limit):
            tree = tree.limit(limit)
        return tree
    return exp.select("*").from_(tree.subquery("capped")).limit(limit)
