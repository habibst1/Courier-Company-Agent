"""Checks LLM-written SQL before it reaches the database sandbox.

The database enforces the real boundary (db/sandbox.sql): the sandbox role can only read
views that are already filtered to the current chat. This module is the first line: it accepts
a single plain SELECT over those views and nothing else, so mistakes and prompt-injection
attempts fail fast with a message the SQL sub-agent can act on. It also caps the row count.

The returned SQL is regenerated by sqlglot from the checked syntax tree, so what runs is
exactly what was checked.
"""

from __future__ import annotations

import re

import sqlglot
from sqlglot import exp
from sqlglot.errors import SqlglotError

ALLOWED_VIEWS = frozenset({"shipments", "tracking_events", "my_addresses", "my_account"})
ALLOWED_SCHEMAS = frozenset({"", "agent"})
MAX_QUERY_CHARS = 4000

# PostgreSQL functions that sqlglot doesn't model get through only if listed here. That keeps out
